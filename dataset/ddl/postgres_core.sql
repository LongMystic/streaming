CREATE TABLE custody.positions (
    account_id         bigint        NOT NULL REFERENCES account.accounts,
    instrument_id      integer       NOT NULL REFERENCES product.instruments,
    total_quantity     bigint        NOT NULL DEFAULT 0,
    available_quantity bigint        NOT NULL DEFAULT 0,
    receiving_quantity bigint        NOT NULL DEFAULT 0,
    blocked_quantity   bigint        NOT NULL DEFAULT 0,
    pledged_quantity   bigint        NOT NULL DEFAULT 0,
    average_cost       numeric(18,4) NOT NULL DEFAULT 0,
    updated_at         timestamptz   NOT NULL DEFAULT now(),
    version            integer       NOT NULL DEFAULT 1,
    PRIMARY KEY (account_id, instrument_id),
    CHECK (available_quantity >= 0 AND total_quantity >= 0)
);
COMMENT ON TABLE  custody.positions IS 'Current securities holdings per account and instrument (mutable snapshot)';
COMMENT ON COLUMN custody.positions.available_quantity IS 'Quantity that can be sold now (co the ban)';
