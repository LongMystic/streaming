CREATE TABLE margin.loan_products (
    loan_product_id         smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_product_code       varchar(30)   NOT NULL UNIQUE,
    name                    varchar(200)  NOT NULL,
    annual_interest_rate_pct numeric(9,6) NOT NULL,
    overdue_interest_rate_pct numeric(9,6) NOT NULL,
    initial_margin_ratio_pct numeric(5,2) NOT NULL,
    maintenance_ratio_pct   numeric(5,2)  NOT NULL,
    force_sell_ratio_pct    numeric(5,2)  NOT NULL,
    max_loan_amount         numeric(20,2) NOT NULL,
    loan_term_days          smallint      NOT NULL,
    effective_from          date          NOT NULL,
    effective_to            date,
    CHECK (initial_margin_ratio_pct > maintenance_ratio_pct AND maintenance_ratio_pct > force_sell_ratio_pct)
);
COMMENT ON TABLE  margin.loan_products IS 'Margin lending packages offered to customers';
COMMENT ON COLUMN margin.loan_products.maintenance_ratio_pct IS 'When the account margin ratio falls below this, a margin call is issued (ty le duy tri)';
COMMENT ON COLUMN margin.loan_products.force_sell_ratio_pct IS 'When the margin ratio falls below this, positions are force-sold (ty le xu ly)';

CREATE TABLE margin.marginable_instruments (
    loan_product_id    smallint     NOT NULL REFERENCES margin.loan_products,
    instrument_id      integer      NOT NULL REFERENCES product.instruments,
    loan_ratio_pct     numeric(5,2) NOT NULL CHECK (loan_ratio_pct BETWEEN 0 AND 50),
    max_price          numeric(18,4),
    effective_from     date         NOT NULL,
    effective_to       date,
    PRIMARY KEY (loan_product_id, instrument_id, effective_from)
);
COMMENT ON TABLE  margin.marginable_instruments IS 'Securities eligible for margin lending and their loan ratio per package (danh muc ky quy)';
COMMENT ON COLUMN margin.marginable_instruments.loan_ratio_pct IS 'Share of the collateral value that can be lent, regulatory cap 50%';

CREATE TABLE margin.loans (
    loan_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id         bigint        NOT NULL REFERENCES account.accounts,
    loan_product_id    smallint      NOT NULL REFERENCES margin.loan_products,
    principal_amount   numeric(20,2) NOT NULL CHECK (principal_amount > 0),
    outstanding_amount numeric(20,2) NOT NULL CHECK (outstanding_amount >= 0),
    annual_interest_rate_pct numeric(9,6) NOT NULL,
    disbursed_at       timestamptz   NOT NULL,
    due_date           date          NOT NULL,
    status             varchar(20)   NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','REPAID','OVERDUE','FORCE_SOLD','WRITTEN_OFF')),
    closed_at          timestamptz,
    created_at         timestamptz   NOT NULL DEFAULT now(),
    updated_at         timestamptz   NOT NULL DEFAULT now(),
    version            integer       NOT NULL DEFAULT 1
);
COMMENT ON TABLE margin.loans IS 'Margin loans; one loan per disbursement (usually created when a margin buy order is settled)';
CREATE INDEX ON margin.loans (account_id, status);

CREATE TABLE margin.interest_accruals (
    loan_id             bigint        NOT NULL REFERENCES margin.loans,
    accrual_date        date          NOT NULL,
    outstanding_amount  numeric(20,2) NOT NULL,
    interest_amount     numeric(20,2) NOT NULL,
    is_overdue          boolean       NOT NULL DEFAULT false,
    PRIMARY KEY (loan_id, accrual_date)
);
COMMENT ON TABLE margin.interest_accruals IS 'Daily interest accrual per loan (calendar days, actual/365)';

CREATE TABLE margin.margin_calls (
    margin_call_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
