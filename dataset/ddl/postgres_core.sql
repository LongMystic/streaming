CREATE TABLE account.accounts (
    account_id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_no               varchar(12)  NOT NULL UNIQUE,
    customer_id              bigint       NOT NULL REFERENCES customer.customers,
    account_type             varchar(20)  NOT NULL CHECK (account_type IN ('CASH','MARGIN','BOND','FUND')),
