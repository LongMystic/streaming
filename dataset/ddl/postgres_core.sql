-- =====================================================================
-- Securities brokerage - CORE / BACK-OFFICE (PostgreSQL 17)
--
-- Owns: reference data, products & market data (EOD), customers & KYC,
-- accounts, cash ledger, custody & settlement, margin lending,
-- corporate actions, CRM, compliance (AML) and unstructured content.
--
-- The trading system (OMS) lives in MySQL (see mysql_oms.sql). Columns
-- such as custody.settlement_instructions.execution_id refer to rows in
-- that database: they are logical references, there is no cross-DB FK.
--
-- Conventions
--   * snake_case, plural table names, surrogate key <entity>_id
--   * GENERATED BY DEFAULT AS IDENTITY: the data generator may supply ids
--   * enums are varchar + CHECK (not PG ENUM) so CDC and schema changes stay simple
--   * money numeric(20,2) VND, price numeric(18,4), quantity bigint, rate numeric(9,6)
--   * all timestamps are timestamptz (UTC); business dates are separate DATE columns
--   * mutable tables carry updated_at + version (optimistic locking)
--   * [PII] in a column comment marks personal data (masking / governance demos)
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS ref;
CREATE SCHEMA IF NOT EXISTS product;
CREATE SCHEMA IF NOT EXISTS customer;
CREATE SCHEMA IF NOT EXISTS account;
CREATE SCHEMA IF NOT EXISTS ledger;
CREATE SCHEMA IF NOT EXISTS custody;
CREATE SCHEMA IF NOT EXISTS margin;
CREATE SCHEMA IF NOT EXISTS corp_action;
CREATE SCHEMA IF NOT EXISTS crm;
CREATE SCHEMA IF NOT EXISTS compliance;
CREATE SCHEMA IF NOT EXISTS content;

COMMENT ON SCHEMA ref         IS 'Reference data: exchanges, trading calendar, sectors, branches, employees';
COMMENT ON SCHEMA product     IS 'Financial products: issuers, instruments and their details, end-of-day prices, fund NAV, fees';
COMMENT ON SCHEMA customer    IS 'Customers (investors), identity documents, addresses, bank accounts, KYC profiles';
COMMENT ON SCHEMA account     IS 'Trading accounts (sub-accounts) of customers';
COMMENT ON SCHEMA ledger      IS 'Cash balances and the append-only cash transaction journal';
COMMENT ON SCHEMA custody     IS 'Securities positions, position movements and T+2 settlement';
COMMENT ON SCHEMA margin      IS 'Margin lending: loan products, marginable list, loans, interest, margin calls';
COMMENT ON SCHEMA corp_action IS 'Corporate actions (dividends, rights issues, splits) and holder entitlements';
COMMENT ON SCHEMA crm         IS 'Customer support tickets, ticket messages and relationship-manager notes';
COMMENT ON SCHEMA compliance  IS 'Anti-money-laundering rules and alerts';
COMMENT ON SCHEMA content     IS 'Unstructured text: news, issuer disclosures, research reports, product documents';

-- ---------------------------------------------------------------------
-- ref
-- ---------------------------------------------------------------------
CREATE TABLE ref.exchanges (
    exchange_code   varchar(10)  PRIMARY KEY,
    name            varchar(200) NOT NULL,
    price_band_pct  numeric(5,2) NOT NULL,
    lot_size        integer      NOT NULL,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    updated_at      timestamptz  NOT NULL DEFAULT now()
);
COMMENT ON TABLE  ref.exchanges IS 'Stock exchanges (san giao dich): HOSE, HNX, UPCOM';
COMMENT ON COLUMN ref.exchanges.price_band_pct IS 'Daily price limit vs reference price (bien do), e.g. HOSE 7.00, HNX 10.00, UPCOM 15.00';
COMMENT ON COLUMN ref.exchanges.lot_size IS 'Board lot (lo chan), number of shares per round lot';

CREATE TABLE ref.trading_calendar (
    calendar_date   date        NOT NULL,
    exchange_code   varchar(10) NOT NULL REFERENCES ref.exchanges,
    is_trading_day  boolean     NOT NULL,
    holiday_name    varchar(200),
    PRIMARY KEY (calendar_date, exchange_code)
);
COMMENT ON TABLE ref.trading_calendar IS 'One row per calendar day and exchange; weekends and public holidays have is_trading_day = false';

CREATE TABLE ref.sectors (
    sector_code         varchar(10)  PRIMARY KEY,
    parent_sector_code  varchar(10)  REFERENCES ref.sectors,
    level               smallint     NOT NULL CHECK (level BETWEEN 1 AND 4),
    name_en             varchar(200) NOT NULL,
    name_vi             varchar(200) NOT NULL
);
COMMENT ON TABLE ref.sectors IS 'Industry classification tree (ICB-like), level 1 = industry ... level 4 = sub-sector';

CREATE TABLE ref.branches (
    branch_id    smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_code  varchar(10)  NOT NULL UNIQUE,
    name         varchar(200) NOT NULL,
    province     varchar(100) NOT NULL,
    opened_on    date         NOT NULL
);
COMMENT ON TABLE ref.branches IS 'Branches / transaction offices of the brokerage';

CREATE TABLE ref.employees (
    employee_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code  varchar(20)  NOT NULL UNIQUE,
    full_name      varchar(200) NOT NULL,
    email          varchar(200) NOT NULL UNIQUE,
    role           varchar(30)  NOT NULL CHECK (role IN ('BROKER','RELATIONSHIP_MANAGER','OPERATIONS','COMPLIANCE','ANALYST','SUPPORT')),
    branch_id      smallint     NOT NULL REFERENCES ref.branches,
    hired_on       date         NOT NULL,
    terminated_on  date,
    status         varchar(20)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
    created_at     timestamptz  NOT NULL DEFAULT now(),
    updated_at     timestamptz  NOT NULL DEFAULT now()
);
COMMENT ON TABLE  ref.employees IS 'Staff: brokers, relationship managers (RM), operations, compliance, analysts, support agents';
COMMENT ON COLUMN ref.employees.full_name IS '[PII] Employee full name';

-- ---------------------------------------------------------------------
-- product
-- ---------------------------------------------------------------------
CREATE TABLE product.issuers (
    issuer_id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    short_name             varchar(100) NOT NULL UNIQUE,
    legal_name             varchar(300) NOT NULL,
    sector_code            varchar(10)  REFERENCES ref.sectors,
    tax_code               varchar(20)  NOT NULL UNIQUE,
    headquarters_province  varchar(100),
    founded_year           smallint,
    charter_capital        numeric(20,2),
    website                varchar(200),
    description            text,
    created_at             timestamptz  NOT NULL DEFAULT now(),
    updated_at             timestamptz  NOT NULL DEFAULT now()
);
COMMENT ON TABLE  product.issuers IS 'Issuers of securities: listed companies, bond issuers, fund management companies. All issuers are fictional';
COMMENT ON COLUMN product.issuers.charter_capital IS 'Charter capital (von dieu le) in VND';

CREATE TABLE product.instruments (
    instrument_id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol                       varchar(20)  NOT NULL UNIQUE,
    isin                         char(12)     UNIQUE,
    instrument_type              varchar(20)  NOT NULL CHECK (instrument_type IN ('STOCK','ETF','COVERED_WARRANT','BOND','FUND_CERTIFICATE')),
    exchange_code                varchar(10)  REFERENCES ref.exchanges,
    issuer_id                    integer      REFERENCES product.issuers,
    name                         varchar(300) NOT NULL,
    currency_code                char(3)      NOT NULL DEFAULT 'VND',
    lot_size                     integer      NOT NULL DEFAULT 100,
    listed_shares                bigint,
    foreign_ownership_limit_pct  numeric(5,2),
    status                       varchar(20)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','SUSPENDED','DELISTED','MATURED')),
    listed_on                    date,
    delisted_on                  date,
    created_at                   timestamptz  NOT NULL DEFAULT now(),
    updated_at                   timestamptz  NOT NULL DEFAULT now(),
    version                      integer      NOT NULL DEFAULT 1
);
COMMENT ON TABLE  product.instruments IS 'Tradable financial instruments (ma chung khoan). exchange_code is NULL for open-ended fund certificates traded through the fund distributor';
COMMENT ON COLUMN product.instruments.symbol IS 'Ticker, e.g. a 3-letter stock code, ETF code, covered warrant code CXXX2501';
COMMENT ON COLUMN product.instruments.foreign_ownership_limit_pct IS 'Foreign ownership limit (room ngoai) as % of listed shares';
CREATE INDEX ON product.instruments (issuer_id);
CREATE INDEX ON product.instruments (exchange_code, instrument_type);

CREATE TABLE product.bond_details (
    instrument_id       integer       PRIMARY KEY REFERENCES product.instruments,
    bond_type           varchar(20)   NOT NULL CHECK (bond_type IN ('GOVERNMENT','CORPORATE')),
    face_value          numeric(20,2) NOT NULL,
    coupon_rate_pct     numeric(9,6)  NOT NULL,
    coupon_frequency    smallint      NOT NULL CHECK (coupon_frequency IN (1,2,4,12)),
    issue_date          date          NOT NULL,
    maturity_date       date          NOT NULL,
    credit_rating       varchar(10),
    is_secured          boolean       NOT NULL DEFAULT false,
    CHECK (maturity_date > issue_date)
);
COMMENT ON TABLE  product.bond_details IS 'Bond-specific attributes, 1-1 with product.instruments where instrument_type = BOND';
COMMENT ON COLUMN product.bond_details.coupon_frequency IS 'Coupon payments per year';

CREATE TABLE product.fund_details (
    instrument_id           integer      PRIMARY KEY REFERENCES product.instruments,
    fund_type               varchar(20)  NOT NULL CHECK (fund_type IN ('EQUITY','BOND','BALANCED','MONEY_MARKET')),
    management_fee_pct      numeric(9,6) NOT NULL,
    subscription_fee_pct    numeric(9,6) NOT NULL DEFAULT 0,
    redemption_fee_pct      numeric(9,6) NOT NULL DEFAULT 0,
    nav_frequency           varchar(10)  NOT NULL CHECK (nav_frequency IN ('DAILY','WEEKLY')),
    inception_date          date         NOT NULL
);
COMMENT ON TABLE product.fund_details IS 'Open-ended fund / ETF attributes; the fund manager is product.instruments.issuer_id';

CREATE TABLE product.warrant_details (
    instrument_id             integer       PRIMARY KEY REFERENCES product.instruments,
    underlying_instrument_id  integer       NOT NULL REFERENCES product.instruments,
    warrant_type              varchar(10)   NOT NULL DEFAULT 'CALL' CHECK (warrant_type IN ('CALL','PUT')),
    exercise_price            numeric(18,4) NOT NULL,
    conversion_ratio          numeric(9,4)  NOT NULL,
    issue_date                date          NOT NULL,
    maturity_date             date          NOT NULL,
    last_trading_date         date          NOT NULL
);
COMMENT ON TABLE  product.warrant_details IS 'Covered warrant (chung quyen co bao dam) attributes; issuer_id on the instrument is the issuing securities company';
COMMENT ON COLUMN product.warrant_details.conversion_ratio IS 'Number of warrants needed for one underlying share, e.g. 4.0 means 4:1';

CREATE TABLE product.eod_prices (
    instrument_id        integer       NOT NULL REFERENCES product.instruments,
    trade_date           date          NOT NULL,
    reference_price      numeric(18,4) NOT NULL,
    ceiling_price        numeric(18,4) NOT NULL,
    floor_price          numeric(18,4) NOT NULL,
    open_price           numeric(18,4),
    high_price           numeric(18,4),
    low_price            numeric(18,4),
    close_price          numeric(18,4),
    volume               bigint        NOT NULL DEFAULT 0,
    trading_value        numeric(22,2) NOT NULL DEFAULT 0,
    foreign_buy_volume   bigint        NOT NULL DEFAULT 0,
    foreign_sell_volume  bigint        NOT NULL DEFAULT 0,
    created_at           timestamptz   NOT NULL DEFAULT now(),
    PRIMARY KEY (instrument_id, trade_date),
    CHECK (floor_price <= reference_price AND reference_price <= ceiling_price)
);
COMMENT ON TABLE  product.eod_prices IS 'End-of-day price board per instrument. Intraday ticks are not stored here: they flow through Kafka topic marketdata.ticks';
COMMENT ON COLUMN product.eod_prices.reference_price IS 'Reference price (gia tham chieu), usually the previous close, adjusted on ex-dates';
COMMENT ON COLUMN product.eod_prices.ceiling_price IS 'Ceiling price (gia tran) = reference * (1 + price band)';
COMMENT ON COLUMN product.eod_prices.floor_price IS 'Floor price (gia san) = reference * (1 - price band)';
COMMENT ON COLUMN product.eod_prices.trading_value IS 'Total matched value in VND (gia tri giao dich)';
CREATE INDEX ON product.eod_prices (trade_date);

CREATE TABLE product.fund_navs (
    instrument_id  integer       NOT NULL REFERENCES product.instruments,
    nav_date       date          NOT NULL,
    nav_per_unit   numeric(18,4) NOT NULL,
    total_nav      numeric(22,2) NOT NULL,
    PRIMARY KEY (instrument_id, nav_date)
);
COMMENT ON TABLE product.fund_navs IS 'Net asset value of open-ended funds per valuation date';

CREATE TABLE product.financial_statements (
    issuer_id             integer       NOT NULL REFERENCES product.issuers,
    fiscal_year           smallint      NOT NULL,
    fiscal_quarter        smallint      NOT NULL CHECK (fiscal_quarter BETWEEN 0 AND 4),
    revenue               numeric(22,2),
    gross_profit          numeric(22,2),
    net_income            numeric(22,2),
    total_assets          numeric(22,2),
    total_liabilities     numeric(22,2),
    owner_equity          numeric(22,2),
    operating_cash_flow   numeric(22,2),
    eps                   numeric(18,4),
    is_audited            boolean       NOT NULL DEFAULT false,
    published_on          date          NOT NULL,
    PRIMARY KEY (issuer_id, fiscal_year, fiscal_quarter)
);
COMMENT ON TABLE  product.financial_statements IS 'Key financial statement figures of issuers (bao cao tai chinh), in VND';
COMMENT ON COLUMN product.financial_statements.fiscal_quarter IS '1-4 for quarterly reports, 0 for the full-year report';

CREATE TABLE product.fee_schedules (
    fee_schedule_id     smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fee_schedule_code   varchar(30)   NOT NULL UNIQUE,
    name                varchar(200)  NOT NULL,
    channel             varchar(20)   CHECK (channel IN ('WEB','MOBILE','BROKER','API')),
    trading_fee_pct     numeric(9,6)  NOT NULL,
    min_fee_per_order   numeric(20,2) NOT NULL DEFAULT 0,
    effective_from      date          NOT NULL,
    effective_to        date,
    CHECK (effective_to IS NULL OR effective_to > effective_from)
);
COMMENT ON TABLE  product.fee_schedules IS 'Brokerage fee packages; channel NULL means the package applies to every channel';
COMMENT ON COLUMN product.fee_schedules.trading_fee_pct IS 'Brokerage fee as % of matched value, e.g. 0.150000';

