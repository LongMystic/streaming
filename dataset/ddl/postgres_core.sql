COMMENT ON TABLE  margin.margin_calls IS 'Margin calls (call ky quy). status records how the call was resolved; FORCE_SOLD is the credit-risk label';
COMMENT ON COLUMN margin.margin_calls.margin_ratio_pct IS 'Account margin ratio at call time = equity / total collateral value * 100';
