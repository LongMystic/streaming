CREATE TABLE customer.bank_accounts (
    bank_account_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      bigint       NOT NULL REFERENCES customer.customers,
    bank_code        varchar(20)  NOT NULL,
    account_number   varchar(30)  NOT NULL,
    account_name     varchar(300) NOT NULL,
    is_default       boolean      NOT NULL DEFAULT false,
    verified_at      timestamptz,
    created_at       timestamptz  NOT NULL DEFAULT now(),
    UNIQUE (bank_code, account_number)
);
COMMENT ON TABLE  customer.bank_accounts IS 'Linked bank accounts used for cash deposits and withdrawals';
COMMENT ON COLUMN customer.bank_accounts.account_number IS '[PII] Bank account number';
CREATE INDEX ON customer.bank_accounts (customer_id);

CREATE TABLE customer.kyc_profiles (
    kyc_profile_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id             bigint       NOT NULL REFERENCES customer.customers,
    risk_rating             varchar(10)  NOT NULL CHECK (risk_rating IN ('LOW','MEDIUM','HIGH')),
    risk_appetite           varchar(20)  NOT NULL CHECK (risk_appetite IN ('CONSERVATIVE','BALANCED','AGGRESSIVE')),
    investment_experience   varchar(20)  NOT NULL CHECK (investment_experience IN ('NONE','UNDER_1Y','1_3Y','3_5Y','OVER_5Y')),
    investment_objective    varchar(30)  NOT NULL CHECK (investment_objective IN ('CAPITAL_PRESERVATION','INCOME','GROWTH','SPECULATION')),
    source_of_funds         varchar(30)  NOT NULL CHECK (source_of_funds IN ('SALARY','BUSINESS','INVESTMENT','INHERITANCE','OTHER')),
    is_pep                  boolean      NOT NULL DEFAULT false,
    is_professional_investor boolean     NOT NULL DEFAULT false,
    reviewed_by_employee_id integer      REFERENCES ref.employees,
    valid_from              timestamptz  NOT NULL,
    valid_to                timestamptz,
    CHECK (valid_to IS NULL OR valid_to > valid_from)
);
COMMENT ON TABLE  customer.kyc_profiles IS 'KYC / suitability profile history (SCD type 2). The current profile has valid_to IS NULL';
COMMENT ON COLUMN customer.kyc_profiles.risk_rating IS 'AML risk rating assigned by compliance';
COMMENT ON COLUMN customer.kyc_profiles.is_pep IS 'Politically exposed person';
COMMENT ON COLUMN customer.kyc_profiles.is_professional_investor IS 'Professional securities investor status (allowed to buy private corporate bonds)';
CREATE UNIQUE INDEX kyc_profiles_one_current ON customer.kyc_profiles (customer_id) WHERE valid_to IS NULL;

