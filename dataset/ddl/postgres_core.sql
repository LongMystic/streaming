CREATE TABLE customer.customers (
    customer_id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_code           varchar(20)  NOT NULL UNIQUE,
    custody_code            varchar(10)  NOT NULL UNIQUE CHECK (custody_code ~ '^[0-9A-Z]{3}[CFP][0-9]{6}$'),
    customer_type           varchar(20)  NOT NULL CHECK (customer_type IN ('INDIVIDUAL','INSTITUTION')),
    full_name               varchar(300) NOT NULL,
    date_of_birth           date,
    gender                  varchar(10)  CHECK (gender IN ('MALE','FEMALE','OTHER')),
    nationality             char(2)      NOT NULL DEFAULT 'VN',
    is_foreign              boolean      NOT NULL DEFAULT false,
    foreign_trading_code    varchar(20)  UNIQUE,
    occupation              varchar(100),
    annual_income_band      varchar(20)  CHECK (annual_income_band IN ('UNDER_200M','200M_500M','500M_1B','1B_5B','OVER_5B')),
    email                   varchar(200),
    phone                   varchar(20),
    status                  varchar(20)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('PENDING','ACTIVE','DORMANT','BLOCKED','CLOSED')),
    onboarding_channel      varchar(20)  NOT NULL CHECK (onboarding_channel IN ('BRANCH','EKYC_MOBILE','EKYC_WEB','PARTNER')),
    referred_by_customer_id bigint       REFERENCES customer.customers,
    rm_employee_id          integer      REFERENCES ref.employees,
    branch_id               smallint     NOT NULL REFERENCES ref.branches,
    opened_at               timestamptz  NOT NULL,
    closed_at               timestamptz,
    created_at              timestamptz  NOT NULL DEFAULT now(),
    updated_at              timestamptz  NOT NULL DEFAULT now(),
    version                 integer      NOT NULL DEFAULT 1,
    CHECK (NOT is_foreign OR foreign_trading_code IS NOT NULL)
);
COMMENT ON TABLE  customer.customers IS 'Investors (khach hang / nha dau tu), individual or institutional, domestic or foreign';
COMMENT ON COLUMN customer.customers.custody_code IS 'Securities custody code (so luu ky): 3-char broker code + C (domestic) / F (foreign) / P (proprietary) + 6 digits';
COMMENT ON COLUMN customer.customers.foreign_trading_code IS 'Trading code issued to foreign investors by the depository (VSDC); required when is_foreign';
COMMENT ON COLUMN customer.customers.full_name IS '[PII] Full name of the individual or legal name of the institution';
COMMENT ON COLUMN customer.customers.date_of_birth IS '[PII] Date of birth, NULL for institutions';
COMMENT ON COLUMN customer.customers.email IS '[PII] Contact email';
COMMENT ON COLUMN customer.customers.phone IS '[PII] Mobile phone';
COMMENT ON COLUMN customer.customers.status IS 'DORMANT = no activity for a long period; BLOCKED = frozen by compliance or operations';
COMMENT ON COLUMN customer.customers.rm_employee_id IS 'Relationship manager / broker in charge of the customer';
CREATE INDEX ON customer.customers (rm_employee_id);
CREATE INDEX ON customer.customers (branch_id);
CREATE INDEX ON customer.customers (status);

