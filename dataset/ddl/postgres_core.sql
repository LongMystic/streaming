CREATE TABLE ledger.cash_balances (
    account_id           bigint        PRIMARY KEY REFERENCES account.accounts,
    available_amount     numeric(20,2) NOT NULL DEFAULT 0,
    blocked_amount       numeric(20,2) NOT NULL DEFAULT 0,
    receivable_amount    numeric(20,2) NOT NULL DEFAULT 0,
    payable_amount       numeric(20,2) NOT NULL DEFAULT 0,
    updated_at           timestamptz   NOT NULL DEFAULT now(),
    version              integer       NOT NULL DEFAULT 1,
    CHECK (available_amount >= 0 AND blocked_amount >= 0)
);
COMMENT ON TABLE  ledger.cash_balances IS 'Current cash state per account (mutable snapshot, high update rate). History is in ledger.cash_transactions';
COMMENT ON COLUMN ledger.cash_balances.blocked_amount IS 'Cash on hold for open buy orders and pending withdrawals';
COMMENT ON COLUMN ledger.cash_balances.receivable_amount IS 'Sale proceeds waiting for T+2 settlement (tien cho ve)';
COMMENT ON COLUMN ledger.cash_balances.payable_amount IS 'Purchase amounts waiting for T+2 settlement';

CREATE TABLE ledger.cash_transactions (
    cash_txn_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id       bigint        NOT NULL REFERENCES account.accounts,
    txn_type         varchar(30)   NOT NULL CHECK (txn_type IN (
                         'DEPOSIT','WITHDRAWAL','BUY_SETTLEMENT','SELL_SETTLEMENT','TRADING_FEE','SELLING_TAX',
                         'CASH_DIVIDEND','DIVIDEND_TAX','MARGIN_INTEREST','LOAN_DISBURSEMENT','LOAN_REPAYMENT',
                         'INTERNAL_TRANSFER_IN','INTERNAL_TRANSFER_OUT','FUND_SUBSCRIPTION','FUND_REDEMPTION','ADJUSTMENT')),
    amount           numeric(20,2) NOT NULL CHECK (amount <> 0),
    balance_after    numeric(20,2) NOT NULL,
    value_date       date          NOT NULL,
    reference_type   varchar(30),
    reference_id     varchar(50),
    bank_account_id  bigint        REFERENCES customer.bank_accounts,
    channel          varchar(20)   CHECK (channel IN ('WEB','MOBILE','BRANCH','BANK_TRANSFER','SYSTEM')),
    description      varchar(500),
    created_at       timestamptz   NOT NULL DEFAULT now()
);
COMMENT ON TABLE  ledger.cash_transactions IS 'Append-only cash journal. amount is signed: positive = money in, negative = money out';
COMMENT ON COLUMN ledger.cash_transactions.reference_type IS 'Source of the entry: SETTLEMENT, CORPORATE_ACTION, LOAN, BANK_TRANSFER, ...';
COMMENT ON COLUMN ledger.cash_transactions.reference_id IS 'Id in the source table, e.g. settlement_id or entitlement_id';
CREATE INDEX ON ledger.cash_transactions (account_id, created_at);
CREATE INDEX ON ledger.cash_transactions (value_date, txn_type);

