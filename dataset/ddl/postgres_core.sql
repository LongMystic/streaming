    issued_place     varchar(200),
    expires_on       date,
    is_primary       boolean      NOT NULL DEFAULT true,
    created_at       timestamptz  NOT NULL DEFAULT now(),
    UNIQUE (document_type, document_number)
);
COMMENT ON TABLE  customer.identity_documents IS 'Identity documents: citizen ID card (CCCD, 12 digits), passport, business registration';
COMMENT ON COLUMN customer.identity_documents.document_number IS '[PII] Document number';
CREATE INDEX ON customer.identity_documents (customer_id);

CREATE TABLE customer.addresses (
    address_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    bigint       NOT NULL REFERENCES customer.customers,
    address_type   varchar(20)  NOT NULL CHECK (address_type IN ('PERMANENT','CONTACT','REGISTERED_OFFICE')),
    address_line   varchar(300) NOT NULL,
