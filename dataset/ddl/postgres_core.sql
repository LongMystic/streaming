    call_date               date          NOT NULL,
    margin_ratio_pct        numeric(7,2)  NOT NULL,
    required_amount         numeric(20,2) NOT NULL,
    deadline_at             timestamptz   NOT NULL,
    status                  varchar(30)   NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','MET_BY_DEPOSIT','MET_BY_SALE','MET_BY_PRICE_RECOVERY','FORCE_SOLD','CANCELLED')),
    resolved_at             timestamptz,
    notified_channels       varchar(100),
