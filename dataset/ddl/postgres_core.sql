    fee_schedule_id          smallint     NOT NULL REFERENCES product.fee_schedules,
    opened_at                timestamptz  NOT NULL,
    closed_at                timestamptz,
    created_at               timestamptz  NOT NULL DEFAULT now(),
    updated_at               timestamptz  NOT NULL DEFAULT now(),
    version                  integer      NOT NULL DEFAULT 1,
    UNIQUE (customer_id, account_type)
);
COMMENT ON TABLE  account.accounts IS 'Sub-accounts (tieu khoan) of a customer: normal cash account, margin account, bond and fund accounts';
COMMENT ON COLUMN account.accounts.account_no IS 'custody_code + 1-digit sub-account suffix, e.g. 058C0012341 (cash) / 058C0012346 (margin)';
CREATE INDEX ON account.accounts (customer_id);

